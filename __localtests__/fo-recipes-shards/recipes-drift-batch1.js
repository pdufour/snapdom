if (RECIPES.length !== 40) {
  throw new Error(`recipes-drift-batch1.js: expected 40 recipes, got ${RECIPES.length}`)
}

const ids = new Set(RECIPES.map((r) => r.id))
if (ids.size !== 40) {
  throw new Error('recipes-drift-batch1.js: duplicate recipe ids')
}

const seen = new Set()
for (const r of RECIPES) {
  const mp = Array.isArray(r.monkeypatch) ? r.monkeypatch.join(',') : (r.monkeypatch ?? '')
  const key = [
    r.inject,
    r.rasterPatch ?? '',
    mp,
    r.svgRootRound ?? '',
    JSON.stringify(r.harnessSnapdom ?? null),
    JSON.stringify(r.labToCanvasOpts ?? null),
    r.css,
  ].join('\0')
  if (seen.has(key)) {
    throw new Error(`recipes-drift-batch1.js: duplicate recipe key at ${r.id}`)
  }
  seen.add(key)
}

